def noteRejection(request: Request, code: str | None, motivo: str | None) -> None:
    """Deja en la solicitud por qué se rechazó, para el monitor de seguridad (app/api/requestContext.py). No cambia la respuesta."""
    if request is not None:  # algunas pruebas invocan el manejador sin solicitud
        request.state.rejection = (code, motivo)


async def validationErrorHandler(request: Request, error: RequestValidationError) -> JSONResponse:
    """422 sin el campo "input": nunca se devuelve el valor recibido (contraseñas, correos, datos personales)."""
    noteRejection(request, "VALIDACION_ENTRADA", None)
    detail = [
        {
            "type": item.get("type"),
            "loc": list(item.get("loc", ())),
            "msg": str(item.get("msg", "")).removeprefix("Value error, "),
        }
        for item in error.errors()
    ]
    return JSONResponse(status_code=status.HTTP_422_UNPROCESSABLE_CONTENT, content={"detail": detail})


async def authErrorHandler(request: Request, error: AuthError) -> JSONResponse:
    statusCode = AUTH_ERROR_STATUS.get(error.code, status.HTTP_400_BAD_REQUEST)
    noteRejection(request, error.code, error.motivo)
    headers = {"WWW-Authenticate": "Bearer"} if statusCode == status.HTTP_401_UNAUTHORIZED else {}
    if error.retryAfterSeconds is not None:
        headers["Retry-After"] = str(error.retryAfterSeconds)
    response = JSONResponse(status_code=statusCode, content={"codigo": error.code, "detail": error.message}, headers=headers or None)
    if (statusCode == status.HTTP_401_UNAUTHORIZED and request.url.path.endswith("/auth/refresh") and sessionCookie.cookieModeRequested(request)
            and not (error.motivo or "").startswith("CSRF")):
        sessionCookie.clear(response)  # una cookie vencida, revocada o reutilizada no sirve más: el navegador la descarta (H-09)
    return response
